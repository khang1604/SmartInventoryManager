       ===================================================== */

    INSERT INTO dbo.StockAlerts
    (
        ProductId,
        WarehouseId,
        AlertType,
        CurrentQuantity,
        Threshold,
        IsResolved
    )

    SELECT
        i.ProductId,
        i.WarehouseId,

        CASE
            WHEN i.Quantity = 0
                THEN 'OUT_OF_STOCK'

            WHEN i.Quantity > 0
                 AND i.Quantity <= p.ReorderPoint
                THEN 'LOW_STOCK'

            WHEN i.Quantity > p.MaximumStock
                THEN 'OVERSTOCK'

            ELSE 'LOW_STOCK'
        END,

        i.Quantity,

        CASE
            WHEN i.Quantity = 0
                THEN 0

            WHEN i.Quantity <= p.ReorderPoint
                THEN p.ReorderPoint

            WHEN i.Quantity > p.MaximumStock
                THEN p.MaximumStock

            ELSE NULL
        END,

        0

    FROM dbo.Inventory AS i

    INNER JOIN dbo.Products AS p
        ON p.ProductId = i.ProductId

    WHERE
        i.Quantity = 0

        OR
        (
            i.Quantity > 0
            AND i.Quantity <= p.ReorderPoint
        )

        OR i.Quantity > p.MaximumStock;


